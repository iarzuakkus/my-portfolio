export const translateValue = (value, language) => {
  if (language !== "en") return value;
  if (typeof value === "string") return englishTranslations[value] ?? value;
  if (Array.isArray(value)) return value.map((item) => translateValue(item, language));
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, translateValue(item, language)]),
    );
  }
  return value;
};
